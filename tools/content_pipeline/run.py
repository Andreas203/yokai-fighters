#!/usr/bin/env python3
"""Yokai Fighters content pipeline: crew agents draft card text from the design vault.

    agent file lists its vault notes --> writer reads them whole --> draft + cited lines
        --> code checks + critic (reads its own notes whole) --issues--> writer rewrites ... --> output

There is no index and no search. Each agent's definition in .claude/agents/ names the
vault notes it reads, and the pipeline hands the agent those notes complete.

Usage (from anywhere):
    python tools/content_pipeline/run.py generate                 # write all ten pieces
    python tools/content_pipeline/run.py generate --only modifier-card
    python tools/content_pipeline/run.py critic-test              # feed the critic deliberately broken drafts
    python tools/content_pipeline/run.py notes                    # which agent loads which notes
    python tools/content_pipeline/run.py generate --replay        # rebuild a recorded run without calling a model
    python tools/content_pipeline/run.py install --run NAME       # put a run's passed modifier cards into data/modifiers/

Every run writes runs/<name>/trace.json and trace.md (notes loaded, lines cited,
drafts, critic issues, final text, tokens and cost per step) plus llm-calls.json for --replay.
Standard library only; live runs need the `claude` CLI, logged in.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from content import CONTENT_TYPES, CRITIC, LAYOUTS, revision_prompt, writer_system, writing_prompt  # noqa: E402
from critic import code_checks, critic_review  # noqa: E402
from llm import LLM, parse_json  # noqa: E402
from vault import ability_names, load_agent_notes  # noqa: E402

ROOT = HERE.parent.parent
VAULT = ROOT / "vault"
AGENTS = ROOT / ".claude" / "agents"
RUNS = HERE / "runs"
VALIDATOR = ROOT / "tools" / "validate_data.py"
FIXTURES = HERE / "seeded_faults.json"
MODIFIERS = ROOT / "data" / "modifiers"


def load_agents() -> dict:
    """Each agent the pipeline runs, with the notes its definition file tells it to read."""
    writers = sorted({ctype["writer"] for ctype in CONTENT_TYPES.values()})
    return {agent: load_agent_notes(VAULT, AGENTS, agent) for agent in writers + [CRITIC]}


def run_item(llm, agents, move_names, type_id, item, args, seeded_draft=None) -> dict:
    ctype = CONTENT_TYPES[type_id]
    writer = ctype["writer"]
    notes = agents[writer]
    evidence = agents[CRITIC]

    layout = args.prompt_layout

    def ask(role, prompt):
        try:
            return parse_json(llm.complete(role, args.writer_model, writer_system(notes, layout), prompt))
        except ValueError:
            return {}

    draft = seeded_draft if seeded_draft is not None else ask("writer", writing_prompt(ctype, item, notes, layout))
    rounds = []
    for n in range(1, args.max_rounds + 1):
        # A seeded draft is written by hand and cites nothing, so its first round skips the cited-line check.
        cites = not (seeded_draft is not None and n == 1)
        code_issues = code_checks(type_id, item, draft, notes, move_names, check_sources=cites)
        review = critic_review(llm, args.critic_model, ctype, item, draft, evidence, layout)
        issues = code_issues + review["issues"]
        rounds.append({"round": n, "draft": draft, "code_issues": code_issues,
                       "critic_verdict": review["verdict"], "critic_issues": review["issues"]})
        print(f"    round {n}: {len(code_issues)} code issue(s), critic {review['verdict']} with {len(review['issues'])} issue(s)")
        if not issues or n == args.max_rounds:
            break
        draft = ask("reviser", revision_prompt(ctype, item, notes, draft, issues, layout))

    last = rounds[-1]
    passed = not last["code_issues"] and not last["critic_issues"]
    return {
        "id": item["id"], "type": type_id, "label": item["label"], "brief": item["brief"],
        "writer": writer, "notes": [n.id for n in notes],
        "critic": CRITIC, "critic_notes": [n.id for n in evidence],
        "seeded": seeded_draft is not None,
        "rounds": rounds,
        "status": "passed" if passed else "needs_human",
        "corrected": passed and len(rounds) > 1,
        "final": assemble(type_id, item, last["draft"], writer, [n.id for n in notes], args.run),
    }


def assemble(type_id: str, item: dict, draft: dict, writer: str, note_ids: list[str], run: str) -> dict:
    """Wrap the model's text in the game's data shape. Ids, triggers and rule lists never come from the model."""
    note = (f"Generated by tools/content_pipeline (run {run}): written by {writer} from vault notes "
            + "; ".join(note_ids) + f"; checked by {CRITIC}")
    if type_id == "modifier-card":
        return {"modifier": item["modifier"], "source": item["source"], "status": "proposed",
                "card": {"plain": draft.get("plain", ""), "frames": draft.get("frames", "")},
                "rules": ["A2", "A8", "A10", "A12"], "notes": note}
    card = {"kind": "story_card", "id": item["id"], "status": "proposed", "trigger": item["trigger"]}
    if item.get("title"):
        card["title"] = item["title"]
    card["text"] = draft.get("text", "")
    if type_id == "wake-up-card":
        card.update({"placeholders": ["yokai"], "speaker": "narrator", "rules": ["S1", "S2", "S3", "S4", "M3"]})
    else:
        card.update({"speaker": "narrator", "rules": ["S1", "S2", "Y2", "Y3"]})
    card["notes"] = note
    return card


def write_outputs(results: list[dict], out_dir: Path) -> dict:
    """Write each final piece as JSON and run the repo's schema validator over the story cards."""
    story_files = []
    for r in results:
        path = out_dir / r["type"] / f"{r['id']}.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(r["final"], indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        if r["final"].get("kind") == "story_card":
            story_files.append(str(path))
    if not story_files or not VALIDATOR.exists():
        return {"ran": False, "reason": "no story cards or no validator"}
    proc = subprocess.run([sys.executable, str(VALIDATOR), *story_files], capture_output=True, text=True, encoding="utf-8")
    if proc.returncode == 2:
        return {"ran": False, "reason": proc.stderr.strip()}
    return {"ran": True, "ok": proc.returncode == 0, "files": len(story_files), "report": proc.stdout.strip()[-1500:]}


def recorded_validation(trace_path: Path, results: list[dict]) -> dict | None:
    """The schema check a run recorded, if this replay rebuilt the same pieces and the check ran then."""
    if not trace_path.exists():
        return None
    trace = json.loads(trace_path.read_text(encoding="utf-8"))
    recorded = trace.get("validation", {})
    same = [r["final"] for r in trace.get("results", [])] == [r["final"] for r in results]
    return recorded if same and recorded.get("ran") else None


# ---------- trace rendering ----------

def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def _final_text(result: dict) -> str:
    final = result["final"]
    if "card" in final:
        return f"plain: {final['card']['plain']}\nframes: {final['card']['frames']}"
    return final["text"]


def _draft_text(draft: dict) -> str:
    if "plain" in draft or "frames" in draft:
        return f"plain: {draft.get('plain', '')}<br>frames: {draft.get('frames', '')}"
    return draft.get("text", "(no text)")


def _sources(draft: dict) -> list[tuple[str, str]]:
    out = []
    for s in draft.get("sources") or []:
        if isinstance(s, dict):
            out.append((str(s.get("note", "")), str(s.get("line", ""))))
    return out


def render_trace(meta: dict, results: list[dict], validation: dict | None) -> str:
    lines = [f"# Trace: {meta['run']}", "",
             f"Command: `{meta['command']}`. Writer model: {meta['writer_model']}. Critic model: {meta['critic_model']}.", "",
             "Each agent reads the notes listed under \"Vault notes\" in its definition file, complete.", "",
             "| Agent | Role | Notes it loads | Size |", "|---|---|---|---|"]
    for agent, info in meta["agents"].items():
        lines.append(f"| `{agent}` | {info['role']} | {'<br>'.join(info['notes'])} | {info['chars']:,} characters |")
    lines += ["", "| Piece | Written by | Rounds | Issues caught | Result |", "|---|---|---|---|---|"]
    for r in results:
        caught = sum(len(x["code_issues"]) + len(x["critic_issues"]) for x in r["rounds"])
        result = "corrected, then passed" if r["corrected"] else ("passed first time" if r["status"] == "passed" else "needs a human")
        lines.append(f"| {r['label']} | `{r['writer']}` | {len(r['rounds'])} | {caught} | {result} |")
    cost = meta.get("cost")
    if cost and cost["total"]["calls"]:
        lines += ["", "## Cost of this run", "",
                  "Tokens and USD as `claude -p` reported them for each live call (`total_cost_usd`, API list price).", "",
                  "| Step | Calls | Input | Cache write | Cache read | Output | USD |", "|---|---|---|---|---|---|---|"]
        for name, row in [*cost["by_step"].items(), ("**Total**", cost["total"])]:
            lines.append(f"| {name} | {row['calls']} | {row['input_tokens']:,} | {row['cache_creation_input_tokens']:,} | "
                         f"{row['cache_read_input_tokens']:,} | {row['output_tokens']:,} | ${row['cost_usd']:.4f} |")
        if cost["calls_without_usage"]:
            lines += ["", f"{cost['calls_without_usage']} recorded call(s) predate cost recording and are not counted."]
    if validation and validation.get("ran"):
        lines += ["", f"Schema check (`tools/validate_data.py`) on {validation['files']} story cards: "
                      f"{'all valid' if validation['ok'] else 'ERRORS'}.", "", "```", validation["report"], "```"]
    for r in results:
        lines += ["", f"## {r['label']}", "", f"Brief: {r['brief']}", ""]
        if r["seeded"]:
            lines += ["Round 1's draft is a seeded fault, written by hand to test the critic.", ""]
        lines += ["### Notes loaded, lines cited, output", "",
                  f"| Notes loaded by `{r['writer']}` | Line the writer cited | Output |", "|---|---|---|"]
        loaded = "<br>".join(r["notes"])
        output = _cell(_final_text(r))
        cited = _sources(r["rounds"][-1]["draft"]) or [("", "(none cited)")]
        for i, (note, line) in enumerate(cited):
            where = f"**{note}**<br>" if note else ""
            lines.append(f"| {loaded if i == 0 else ''} | {where}{_cell(line)} | {output if i == 0 else ''} |")
        lines += ["", f"### Critic loop (`{r['critic']}`)", ""]
        for x in r["rounds"]:
            lines += [f"**Round {x['round']} draft:** {_draft_text(x['draft'])}", ""]
            issues = x["code_issues"] + x["critic_issues"]
            if not issues:
                lines += ["Code checks: clean. Critic: pass.", ""]
                continue
            lines += ["| Caught by | Kind | Quote | Problem | Evidence | Fix |", "|---|---|---|---|---|---|"]
            for i in issues:
                lines.append(f"| {i['by']} | {i['kind']} | {_cell(i.get('quote', ''))} | {_cell(i['problem'])} | {_cell(i.get('evidence', ''))} | {_cell(i.get('fix', ''))} |")
            lines.append("")
        lines += [f"**Final ({r['status']}):** {_draft_text(r['rounds'][-1]['draft'])}"]
    return "\n".join(lines) + "\n"


# ---------- commands ----------

def select_items(only: list[str] | None):
    for type_id, ctype in CONTENT_TYPES.items():
        for item in ctype["items"]:
            if not only or type_id in only or item["id"] in only:
                yield type_id, item


def agent_summary(agents: dict) -> dict:
    writes = {}
    for ctype in CONTENT_TYPES.values():
        writes.setdefault(ctype["writer"], []).append(ctype["title"])
    return {agent: {"role": "Critic: checks every draft" if agent == CRITIC else "Writer: " + ", ".join(writes[agent]),
                    "notes": [n.id for n in notes], "chars": sum(len(n.text) for n in notes)}
            for agent, notes in agents.items()}


def cmd_generate(args, agents, move_names):
    run_dir = RUNS / args.run
    run_dir.mkdir(parents=True, exist_ok=True)
    llm = LLM(run_dir / "llm-calls.json", replay=args.replay)
    results = []
    if args.command == "critic-test":
        seeds = json.loads(FIXTURES.read_text(encoding="utf-8"))
        items = {item["id"]: (type_id, item) for type_id, item in select_items(None)}
        work = [(items[s["item"]][0], items[s["item"]][1], s["draft"]) for s in seeds]
    else:
        work = [(type_id, item, None) for type_id, item in select_items(args.only)]
    if not work:
        raise SystemExit("Nothing matched --only. Use a type id or a piece id from content.py.")
    for type_id, item, seeded in work:
        print(f"  {item['label']}")
        results.append(run_item(llm, agents, move_names, type_id, item, args, seeded_draft=seeded))

    validation = write_outputs(results, run_dir / "output")
    kept = False
    if args.replay and not validation.get("ran"):
        recorded = recorded_validation(run_dir / "trace.json", results)
        if recorded:
            skipped, validation, kept = validation.get("reason", ""), recorded, True
    meta = {"run": args.run, "command": args.command, "writer_model": args.writer_model,
            "critic_model": args.critic_model, "agents": agent_summary(agents), "cost": llm.cost_summary()}
    (run_dir / "trace.json").write_text(json.dumps({"meta": meta, "validation": validation, "results": results},
                                                   indent=2, ensure_ascii=False), encoding="utf-8")
    (run_dir / "trace.md").write_text(render_trace(meta, results, validation), encoding="utf-8")

    passed = sum(r["status"] == "passed" for r in results)
    corrected = sum(r["corrected"] for r in results)
    print(f"\n{passed}/{len(results)} passed ({corrected} after correction); "
          f"{llm.live_calls} live model call(s), {llm.replayed_calls} replayed.")
    if kept:
        print(f"Schema check not re-run ({skipped}); kept the recorded result: "
              f"{validation['files']} story cards, {'all valid' if validation['ok'] else 'ERRORS'}")
    elif validation.get("ran"):
        print(f"Schema check on {validation['files']} story cards: {'all valid' if validation['ok'] else 'ERRORS'}")
    total = meta["cost"]["total"]
    if total["calls"]:
        print(f"Cost: ${total['cost_usd']:.4f} over {total['calls']} call(s) "
              f"({total['input_tokens'] + total['cache_creation_input_tokens'] + total['cache_read_input_tokens']:,} tokens in, "
              f"{total['output_tokens']:,} out)")
    print(f"Trace: {run_dir / 'trace.md'}")
    return 0 if passed == len(results) and validation.get("ok", True) else 1


def cmd_install(args) -> int:
    """Put a run's passed modifier cards into the game's own files, data/modifiers/<id>.json.

    The game reads card.plain and card.frames from those files at start-up, so nothing else
    changes: the reward screen shows the new text the next time the game (or an export) runs.
    Story cards are not installed: wake-up variants by yokai have no slot the game reads yet, and
    the elder intro cards in data/story are voiced by the elder (S5), which a narrator card would replace.
    """
    run_dir = RUNS / args.run
    trace_path = run_dir / "trace.json"
    if not trace_path.exists():
        raise SystemExit(f"No run at {run_dir}. Run generate first.")
    results = json.loads(trace_path.read_text(encoding="utf-8"))["results"]
    installed, skipped = [], []
    for r in results:
        if r["type"] != "modifier-card":
            skipped.append((r["id"], "story card: no slot the game reads (see install's docstring)"))
            continue
        if r["status"] != "passed":
            skipped.append((r["id"], "did not pass the critic loop"))
            continue
        target = MODIFIERS / f"{r['id'].removesuffix('-card')}.json"
        if not target.exists():
            skipped.append((r["id"], f"no game file {target.name}"))
            continue
        data = json.loads(target.read_text(encoding="utf-8"))
        before = dict(data.get("card", {}))
        data["card"] = {"plain": r["final"]["card"]["plain"], "frames": r["final"]["card"]["frames"]}
        provenance = f"Card text from tools/content_pipeline run {args.run} (movesmith, checked by rules-lawyer)."
        notes = data.get("notes", "")
        data["notes"] = provenance if not notes else (notes if provenance in notes else f"{notes} {provenance}")
        target.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        installed.append(target)
        print(f"  {target.relative_to(ROOT).as_posix()}")
        print(f"    was: {before.get('plain', '')}")
        print(f"    now: {data['card']['plain']}")
    for item_id, why in skipped:
        print(f"  skipped {item_id}: {why}")
    if not installed:
        return 1
    proc = subprocess.run([sys.executable, str(VALIDATOR), *map(str, installed)], capture_output=True, text=True, encoding="utf-8")
    print(proc.stdout.strip()[-800:] or proc.stderr.strip()[-800:])
    print(f"{len(installed)} modifier card(s) installed into data/modifiers/; the game loads them as they are.")
    return proc.returncode


def cmd_notes(agents):
    for agent, info in agent_summary(agents).items():
        print(f"{agent}  ({info['role']})")
        for note in agents[agent]:
            print(f"    vault/{note.id:<34} {len(note.text):>6,} characters")
        print(f"    {'total':<40} {info['chars']:>6,} characters\n")
    return 0


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("generate", "critic-test"):
        p = sub.add_parser(name)
        p.add_argument("--run", help="run folder name under runs/ (default depends on the command)")
        p.add_argument("--only", nargs="*", help="content type ids or piece ids")
        p.add_argument("--writer-model", default="sonnet")
        p.add_argument("--critic-model", default="opus")
        p.add_argument("--max-rounds", type=int, default=3, help="drafts per piece, including the first")
        p.add_argument("--replay", action="store_true", help="use the run's recorded model calls; call nothing")
        p.add_argument("--prompt-layout", choices=LAYOUTS, default="cached",
                       help="cached: vault notes in the system prompt, read from the prompt cache after the first call "
                            "(default); v1: notes last in the user message, the layout of runs recorded before 2026-11-13")
    sub.add_parser("notes")
    p = sub.add_parser("install")
    p.add_argument("--run", required=True, help="run folder name under runs/")
    args = parser.parse_args()
    if args.command == "install":
        return cmd_install(args)

    agents = load_agents()
    if args.command == "notes":
        return cmd_notes(agents)
    if not args.run:
        args.run = "critic-seeded-faults" if args.command == "critic-test" else "whole-notes"
    print(f"Agents: {', '.join(agents)}. Run: {args.run}")
    return cmd_generate(args, agents, ability_names(VAULT))


if __name__ == "__main__":
    sys.exit(main())
