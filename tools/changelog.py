#!/usr/bin/env python3
"""Generate CHANGELOG.md from merged pull requests (YOK-188). Stdlib only.

Usage:
    python -I tools/changelog.py [--check] [--from-json FILE] [--out FILE]

Merged PRs come from `gh pr list --state merged` unless --from-json gives a saved copy of that output
(fields number, title, body, mergedAt, url). Each PR becomes one line under its build week, newest first:
the text under the PR body's `## Changelog` heading (the PR template's last section), else the title.
A changelog line of `none` leaves the PR out. See docs/process/change-tracking.md.

Exit 0 written (or up to date with --check), 1 out of date with --check, 2 gh failed.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = "number,title,body,mergedAt,url"
# Build weeks end on these dates (Linear milestones: W1 10-10, W2 10-17, W3 10-24, W4-5 11-07).
WEEK_ENDS = [dt.date(2026, 10, 10), dt.date(2026, 10, 17), dt.date(2026, 10, 24),
             dt.date(2026, 10, 31), dt.date(2026, 11, 7)]
HEADER = """# Changelog

Every merged pull request, by build week, newest first. Generated by `tools/changelog.py`: do not edit by hand.
Where each kind of change is recorded: `docs/process/change-tracking.md`.
"""


def week_of(day: dt.date) -> str:
    for n, end in enumerate(WEEK_ENDS, 1):
        if day <= end:
            start = end - dt.timedelta(days=6)
            return f"Week {n} (to {end.isoformat()})" if n == 1 else f"Week {n} ({start.isoformat()} to {end.isoformat()})"
    return "After the build"


def changelog_line(body: str | None) -> str | None:
    """The first non-comment line under `## Changelog`, or None when the section is missing or empty."""
    m = re.search(r"^##\s+Changelog\s*$(.*?)(?=^##\s|\Z)", body or "", flags=re.M | re.S)
    if not m:
        return None
    text = re.sub(r"<!--.*?-->", "", m.group(1), flags=re.S)
    for line in text.splitlines():
        if line.strip():
            return line.strip().lstrip("-* ").strip()
    return None


def entry(pr: dict) -> str | None:
    title = pr["title"].strip()
    m = re.match(r"^(YOK-\d+)-(.+)$", title)
    ticket, brief = (m.group(1), m.group(2)) if m else (None, re.sub(r"^YOK-", "", title))
    line = changelog_line(pr.get("body"))
    if line is not None and line.lower().rstrip(".") == "none":
        return None
    text = line or brief.replace("-", " ")
    day = pr["mergedAt"][:10]
    tag = f"**{ticket}** " if ticket else ""
    return f"- {day} {tag}{text} ([#{pr['number']}]({pr['url']}))"


def render(prs: list[dict]) -> str:
    weeks: dict[str, list[tuple[str, int, str]]] = {}
    order: list[str] = []
    for pr in sorted(prs, key=lambda p: (p["mergedAt"], p["number"]), reverse=True):
        line = entry(pr)
        if line is None:
            continue
        week = week_of(dt.date.fromisoformat(pr["mergedAt"][:10]))
        if week not in weeks:
            weeks[week] = []
            order.append(week)
        weeks[week].append(line)
    out = [HEADER]
    for week in order:
        out.append(f"## {week}\n")
        out.extend(weeks[week])
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def fetch() -> list[dict]:
    proc = subprocess.run(["gh", "pr", "list", "--state", "merged", "--limit", "2000", "--json", FIELDS],
                          capture_output=True, text=True, encoding="utf-8", cwd=ROOT)
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.strip() or "gh pr list failed")
    return json.loads(proc.stdout)


def main(argv: list[str] | None = None, out=sys.stdout) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file is out of date; write nothing")
    ap.add_argument("--from-json", type=Path, help="read the merged PRs from this file instead of gh")
    ap.add_argument("--out", type=Path, default=ROOT / "CHANGELOG.md")
    args = ap.parse_args(argv)
    try:
        prs = json.loads(args.from_json.read_text(encoding="utf-8")) if args.from_json else fetch()
    except (OSError, RuntimeError, json.JSONDecodeError) as e:
        print(f"changelog: {e}", file=out)
        return 2
    text = render(prs)
    current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
    if args.check:
        print("changelog: up to date" if current == text else f"changelog: {args.out.name} is out of date", file=out)
        return 0 if current == text else 1
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"changelog: wrote {sum(1 for l in text.splitlines() if l.startswith('- '))} entries to {args.out.name}", file=out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
